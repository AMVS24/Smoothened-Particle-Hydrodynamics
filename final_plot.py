# ==============================
# FIGURE SETUP
# ==============================
plt.figure(figsize=(9,5.5), dpi=140)
ax = plt.gca()

colors = {
    "naive": "#C44E52",
    "hash": "#4C72B0",
    "vec": "#55A868",
    "taichi": "#8172B2"
}

# ==============================
# SCATTER + CONNECTED LINES
# ==============================
def plot_series(x, y, label, color, lw=2.2):
    ax.plot(x, y, color=color, linewidth=lw, alpha=0.9)
    ax.scatter(x, y, color=color, s=14, label=label, alpha=0.95)

plot_series(particle_counts, naive, "Naive Python", colors["naive"])
plot_series(particle_counts, spatial_hash, "Spatial Hash", colors["hash"])
plot_series(particle_counts, vectorised, "Vectorised NumPy", colors["vec"])
plot_series(particle_counts, taichi, "GPU (Taichi)", colors["taichi"], lw=2.6)

# ==============================
# AXES LIMITS + LABELS
# ==============================
ax.set_xlabel("Particle Count", fontsize=12)
ax.set_ylabel("Total Time per Frame (ms)", fontsize=12)

ax.set_xlim(0, 11000)
ax.set_ylim(0, 2500)

# ==============================
# MAKE TEXTBOOK-STYLE AXES
# ==============================

# remove default box
ax.spines["top"].set_visible(False)
ax.spines["right"].set_visible(False)

# keep only bottom + left as axes lines
ax.spines["bottom"].set_linewidth(1.5)
ax.spines["left"].set_linewidth(1.5)

# force them to cross at origin
ax.spines["bottom"].set_position(("data", 0))
ax.spines["left"].set_position(("data", 0))

# ticks styling
ax.tick_params(axis='both', labelsize=10, width=1.2)

# no grid
ax.grid(False)

# legend
ax.legend(frameon=False, fontsize=11)

plt.tight_layout()

